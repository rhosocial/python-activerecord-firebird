# tests/rhosocial/activerecord_firebird_test/feature/backend/construct/ddl/test_auto_increment_ddl.py
"""Regression tests for DDL compilation of auto-increment, standard types,
boolean defaults, and timestamps.

Covers bugs found in rbac cross-backend testing:
- is_auto_increment=True on PRIMARY_KEY must produce GENERATED BY DEFAULT
  AS IDENTITY (Firebird 3+). Was missing — now fixed.
- format_create_table_statement must return a string for all types.
  Previously col_def.data_type (a type object) was placed directly into
  the parts list instead of calling to_sql(self), causing
  'expected str instance, IntegerType found' in ' '.join(parts).
- BooleanType with DEFAULT True must be accepted.
- TimestampType must map to TIMESTAMP.
"""
from rhosocial.activerecord.backend.suggestion import IntegerAutoIncrementSuggestionRenderer  # noqa: E402

import pytest

from rhosocial.activerecord.backend.expression import (
    CreateTableStatement, ColumnDefinition, ColumnConstraint,
    ColumnDefaultConstraint, ColumnNotNullConstraint, ColumnNullableConstraint,
    ColumnPrimaryKeyConstraint,
)
from rhosocial.activerecord.backend.expression.objects import Table
from rhosocial.activerecord.backend.expression.types import (
    BooleanType, IntegerType, TextType, TimestampType, VarCharType,
)
from rhosocial.activerecord.backend.impl.firebird.dialect import FirebirdDialect


@pytest.fixture
def dialect():
    return FirebirdDialect((3, 0, 0))


def _id_column(dialect, data_type, **kwargs):
    """Build an integer auto-increment id column from the backend suggestion."""
    suggested_type, attributes = IntegerAutoIncrementSuggestionRenderer().parts(dialect, data_type)
    return ColumnDefinition(
        dialect, "id", suggested_type,
        constraints=[ColumnConstraint(dialect, branch=ColumnPrimaryKeyConstraint(dialect))],
        attributes=attributes,
        **kwargs,
    )


def _build_table(dialect):
    return CreateTableStatement(
        dialect=dialect, table=Table(dialect, "test_tbl"),
        columns=[
            _id_column(dialect, IntegerType(dialect)),
            ColumnDefinition(dialect, "name", TextType(dialect),
                constraints=[ColumnConstraint(dialect, branch=ColumnNotNullConstraint(dialect))]),
            ColumnDefinition(dialect, "flag", BooleanType(dialect),
                constraints=[ColumnConstraint(dialect, branch=ColumnNotNullConstraint(dialect)),
                             ColumnConstraint(dialect, branch=ColumnDefaultConstraint(dialect, True))]),
            ColumnDefinition(dialect, "code", VarCharType(length=16, dialect=dialect)),
            ColumnDefinition(dialect, "created_at", TimestampType(dialect=dialect)),
        ],
    )


class TestAutoIncrementDDL:

    def test_auto_increment_in_ddl(self, dialect):
        sql, _ = dialect.format_create_table_statement(_build_table(dialect))
        assert "GENERATED BY DEFAULT AS IDENTITY" in sql.upper(), \
            f"auto-increment missing: {sql}"

    def test_all_standard_types_compile(self, dialect):
        """format_create_table_statement must return str, not type objects."""
        sql, params = dialect.format_create_table_statement(_build_table(dialect))
        assert isinstance(sql, str)
        assert isinstance(params, tuple)

    def test_boolean_default_true(self, dialect):
        expr = CreateTableStatement(
            dialect=dialect, table=Table(dialect, "bool_test"),
            columns=[
                _id_column(dialect, IntegerType(dialect)),
                ColumnDefinition(dialect, "flag", BooleanType(dialect),
                    constraints=[ColumnConstraint(dialect, branch=ColumnNotNullConstraint(dialect)),
                                 ColumnConstraint(dialect, branch=ColumnDefaultConstraint(dialect, True))]),
            ],
        )
        sql, _ = dialect.format_create_table_statement(expr)
        assert "BOOLEAN" in sql.upper()

    def test_timestamp_type(self, dialect):
        expr = CreateTableStatement(
            dialect=dialect, table=Table(dialect, "ts_test"),
            columns=[
                _id_column(dialect, IntegerType(dialect)),
                ColumnDefinition(dialect, "created_at", TimestampType(dialect=dialect)),
            ],
        )
        sql, _ = dialect.format_create_table_statement(expr)
        assert "TIMESTAMP" in sql.upper()

    def test_explicit_null_constraint_is_omitted(self, dialect):
        """Firebird rejects a bare ``NULL`` column clause (SQLCODE -104).

        A nullable column is nullable by default here, so the portable
        `` NULL`` the core DDL mixin emits must be dropped rather than sent to
        the server.
        """
        expr = CreateTableStatement(
            dialect=dialect, table=Table(dialect, "null_test"),
            columns=[
                _id_column(dialect, IntegerType(dialect)),
                ColumnDefinition(dialect, "code", VarCharType(length=16, dialect=dialect),
                    constraints=[ColumnConstraint(dialect, branch=ColumnNullableConstraint(dialect))]),
            ],
        )
        sql, _ = dialect.format_create_table_statement(expr)
        assert " NULL" not in sql.replace(" NOT NULL", "")
