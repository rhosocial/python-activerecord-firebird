# tests/rhosocial/activerecord_firebird_test/feature/backend/ddl/test_typed_model_ddl.py
"""Cross-backend UseSqlType demonstration — Firebird rendering.

The shared ``TypedUser`` model (core generic types) renders Firebird-native
SQL without any per-dialect string mappings. Firebird uppercases identifiers
by default. Dialect instantiation needs no DB server; only ``to_sql()`` is
exercised here.
"""

from rhosocial.activerecord.backend.impl.firebird.dialect import FirebirdDialect
from rhosocial.activerecord.examples.ddl_types import TypedUser


def _render() -> str:
    sql, _ = TypedUser.generate_create_table(dialect=FirebirdDialect()).to_sql()
    return sql


def test_firebird_typed_user_ddl_columns():
    sql = _render()
    assert "CREATE TABLE \"TYPED_USERS\"" in sql
    assert '"ID" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' in sql
    assert '"USERNAME" VARCHAR(100) NOT NULL' in sql
    assert '"EMAIL" VARCHAR(255) NOT NULL' in sql
    assert '"IS_ACTIVE" BOOLEAN NOT NULL' in sql
    assert '"BALANCE" DECIMAL(10, 2)' in sql
    assert '"BIRTHDAY" DATE' in sql
    assert '"CREATED_AT" TIMESTAMP NOT NULL' in sql
    assert '"BIO" BLOB SUB_TYPE TEXT' in sql
    assert '"METADATA" JSON' in sql
    assert '"BIG_COUNTER" BIGINT' in sql
    assert '"AVATAR" BLOB SUB_TYPE BINARY' in sql
    assert '"WAKE_UP_TIME" TIME' in sql


def test_firebird_typed_user_no_per_dialect_string_keys():
    for _field_name, marker in TypedUser.__table_field_sql_types__.items():
        assert not hasattr(marker, "dialect_types")
        assert marker.data_type is not None