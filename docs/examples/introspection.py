# docs/examples/introspection.py
"""Firebird introspection example: catalogue, own families and data families.

Uses backend.introspector against a real database and a declarative model. It
reads the RDB$ catalogue, Firebird's own object families (generators, domains,
routines, dependencies), capability probes, and the three row-measuring data
families. The demo table it creates is dropped on exit.

Run from the repository root with FIREBIRD_* environment variables set (see
connection.py) or with tests/config/firebird_scenarios.yaml available.
"""

import sys
from dataclasses import asdict
from typing import Any, ClassVar, Optional

from rhosocial.activerecord.backend.impl.firebird.backend import FirebirdBackend
from rhosocial.activerecord.backend.impl.firebird.config import FirebirdConnectionConfig
from rhosocial.activerecord.base.field_proxy import FieldProxy
from rhosocial.activerecord.model import ActiveRecord

TABLE = "FB_DEMO_INTROSPECT"

INSTRUCTIONS = """\
No Firebird database is configured. Set FIREBIRD_DATABASE (and the other
FIREBIRD_* variables) or provide tests/config/firebird_scenarios.yaml.
"""


class Reading(ActiveRecord):
    """Small model whose table the introspector will describe and measure."""

    __table_name__ = TABLE
    __primary_key__ = "id"

    c: ClassVar[FieldProxy] = FieldProxy()

    id: Optional[int] = None
    code: str
    bucket: int


def show(label: str, rows: Any, limit: int = 3) -> None:
    """Print a small sample of a list of introspection records."""
    materialized = list(rows)
    print(f"\n{label}: {len(materialized)}")
    for row in materialized[:limit]:
        if hasattr(row, "__dataclass_fields__"):
            print(f"  {asdict(row)}")
        else:
            print(f"  {row}")


def main() -> int:
    config = FirebirdConnectionConfig.from_env()
    if not config.database:
        print(INSTRUCTIONS, file=sys.stderr)
        return 2

    backend = FirebirdBackend(connection_config=config)
    try:
        backend.connect()
        backend.introspect_and_adapt()  # version-sensitive answers need adaptation
    except Exception as exc:
        print(f"Could not connect to Firebird: {exc}", file=sys.stderr)
        print(INSTRUCTIONS, file=sys.stderr)
        return 2

    created_table = False
    try:
        if not backend.introspector.table_exists(TABLE):
            backend.execute(
                f"CREATE TABLE {TABLE} ("
                "ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                "CODE VARCHAR(8) NOT NULL, BUCKET INTEGER NOT NULL)",
                fetch=False,
            )
            created_table = True

        Reading.configure(config, FirebirdBackend)
        for code, bucket in (("alpha", 1), ("beta", 1), ("beta", 2), ("gamma", 2)):
            Reading(code=code, bucket=bucket).save()

        introspector = backend.introspector
        dialect = backend.dialect

        # Capability answers first: a False means "do not ask", not "empty".
        print("Capability gates:")
        print(f"  introspection:      {dialect.supports_introspection()}")
        print(f"  table storage:      {dialect.supports_table_storage_introspection()}")
        print(f"  publications (FB4+): {dialect.supports_publication_introspection()}")

        # Catalogue families (upper-case name: Firebird folds identifiers).
        show("Tables", introspector.list_tables())
        show("Columns", introspector.list_columns(TABLE))
        show("Indexes", introspector.list_indexes(TABLE))
        show("Constraints", introspector.list_constraints(TABLE))

        # Firebird's own object families.
        show("Generators", introspector.list_generators())
        show("Domains", introspector.list_domains())
        show("Procedures", introspector.list_procedures())
        show("RDB$ dependency edges", introspector.list_dependencies())

        # Data families: these measure rows, not the catalogue.
        show("Column profiles", introspector.list_column_data_profiles(TABLE))
        show("Value samples of CODE", introspector.sample_column_values(TABLE, "CODE"))
        coverage = introspector.estimate_join_coverage(
            TABLE, "BUCKET", TABLE, "ID"
        )
        print(f"\nJoin coverage: {asdict(coverage) if coverage else None}")

        print("\nCLI equivalent:")
        print(
            "  python -m rhosocial.activerecord.backend.impl.firebird "
            f"introspect column-profiles {TABLE}"
        )
        return 0
    finally:
        if created_table:
            try:
                backend.execute(f"DROP TABLE {TABLE}", fetch=False)
            except Exception as exc:
                print(f"Could not drop {TABLE}: {exc}", file=sys.stderr)
        backend.disconnect()


if __name__ == "__main__":
    sys.exit(main())
