# docs/examples/ddl.py
"""Firebird DDL example: table, domain, generator and stored procedure.

Demonstrates this backend's own DDL helpers and expression classes alongside a
declarative ActiveRecord model. Every object created here is dropped again on
exit. The whole group is created inside a transaction because Firebird DDL is
transactional on this backend.

Run from the repository root with FIREBIRD_* environment variables set (see
connection.py) or with tests/config/firebird_scenarios.yaml available.
"""

import sys
from typing import ClassVar, Optional

from rhosocial.activerecord.backend.impl.firebird.backend import FirebirdBackend
from rhosocial.activerecord.backend.impl.firebird.config import FirebirdConnectionConfig
from rhosocial.activerecord.backend.impl.firebird.expression.ddl.routine import (
    FirebirdCreateProcedureStatement,
)
from rhosocial.activerecord.backend.impl.firebird.expression.generator import (
    GenIdExpression,
    NextValueForExpression,
)
from rhosocial.activerecord.backend.impl.firebird.types import FirebirdDomainType
from rhosocial.activerecord.base.field_proxy import FieldProxy
from rhosocial.activerecord.model import ActiveRecord

TABLE = "FB_DEMO_WIDGETS"
DOMAIN = "FB_DEMO_POSITIVE_INT"
GENERATOR = "FB_DEMO_WIDGET_GEN"
PROCEDURE = "FB_DEMO_ADD"

INSTRUCTIONS = """\
No Firebird database is configured. Set FIREBIRD_DATABASE (and the other
FIREBIRD_* variables) or provide tests/config/firebird_scenarios.yaml.
"""


class Widget(ActiveRecord):
    """Model whose key is identity-generated and whose qty uses a domain."""

    __table_name__ = TABLE
    __primary_key__ = "id"

    c: ClassVar[FieldProxy] = FieldProxy()

    id: Optional[int] = None
    name: str
    qty: Optional[int] = None  # column declared from DOMAIN


def render(statement) -> str:
    """Render a backend expression through the backend's dialect."""
    sql, params = statement.to_sql()
    assert not params, "DDL expressions in this example take no bind parameters"
    return sql


def main() -> int:
    config = FirebirdConnectionConfig.from_env()
    if not config.database:
        print(INSTRUCTIONS, file=sys.stderr)
        return 2

    backend = FirebirdBackend(connection_config=config)
    try:
        backend.connect()
        backend.introspect_and_adapt()  # adapt the dialect to the server version
    except Exception as exc:
        print(f"Could not connect to Firebird: {exc}", file=sys.stderr)
        print(INSTRUCTIONS, file=sys.stderr)
        return 2

    created = {"table": False, "domain": False, "generator": False, "procedure": False}
    try:
        if backend.introspector.table_exists(TABLE):
            print(f"{TABLE} already exists; nothing to create. Drop it to re-run this example.")
            return 0

        # The domain body is composed by this backend's FirebirdDomainType.
        domain_body = FirebirdDomainType(
            "INTEGER", not_null=True, check="VALUE > 0"
        ).to_sql()
        domain_sql = f"CREATE DOMAIN {DOMAIN} AS {domain_body}"

        # These expressions render through the Firebird dialect.
        gen_id_sql, _ = GenIdExpression(backend.dialect, GENERATOR, step=1).to_sql()
        next_value_sql, _ = NextValueForExpression(backend.dialect, GENERATOR).to_sql()
        procedure_sql = render(
            FirebirdCreateProcedureStatement(
                backend.dialect,
                PROCEDURE,
                params=[("A", "INTEGER"), ("B", "INTEGER")],
                returns=[("RESULT", "INTEGER")],
                body="RESULT = A + B;",
            )
        )

        with backend.transaction():
            backend.execute(domain_sql, fetch=False)
            created["domain"] = True
            backend.execute(f"CREATE GENERATOR {GENERATOR}", fetch=False)
            created["generator"] = True
            backend.execute(
                f"CREATE TABLE {TABLE} ("
                "ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                f"NAME VARCHAR(40) NOT NULL, QTY {DOMAIN})",
                fetch=False,
            )
            created["table"] = True
            backend.execute(procedure_sql, fetch=False)
            created["procedure"] = True

        print("Executed (inside one transaction):")
        print(f"  {domain_sql}")
        print(f"  CREATE GENERATOR {GENERATOR}")
        print(f"  CREATE TABLE {TABLE} (... QTY {DOMAIN} ...)")
        print(f"  {procedure_sql}")
        print("Rendered sequence expressions:")
        print(f"  {gen_id_sql}")
        print(f"  {next_value_sql}")

        # The model uses the domain-typed column declared above.
        Widget.configure(config, FirebirdBackend)
        widget = Widget(name="bolt", qty=25)
        widget.save()
        print(f"Inserted widget id={widget.id} via a domain-typed column")

        result = backend.execute(
            f"SELECT {gen_id_sql} FROM RDB$DATABASE", fetch=True
        )
        print(f"GEN_ID value: {result.data}")
        return 0
    finally:
        # Reverse dependency order: table (uses the domain) first.
        cleanup = [
            ("table", f"DROP TABLE {TABLE}"),
            ("procedure", f"DROP PROCEDURE {PROCEDURE}"),
            ("generator", f"DROP GENERATOR {GENERATOR}"),
            ("domain", f"DROP DOMAIN {DOMAIN}"),
        ]
        for key, sql in cleanup:
            if created[key]:
                try:
                    backend.execute(sql, fetch=False)
                except Exception as exc:
                    print(f"Could not run {sql}: {exc}", file=sys.stderr)
        backend.disconnect()


if __name__ == "__main__":
    sys.exit(main())
