# docs/examples/connection.py
r"""Connection + declarative model example for the Firebird backend.

Requires a reachable Firebird database. Connection settings come from the
FIREBIRD_* environment variables (see the setup instructions printed when none
are configured). The script creates a small demo table only if it does not
already exist, and drops it again on exit when it created it.

Run from the repository root:

    $env:FIREBIRD_DATABASE = 'localhost/3050:/var/lib/firebird/data/test.fdb'
    $env:FIREBIRD_USERNAME = 'SYSDBA'
    $env:FIREBIRD_PASSWORD = 'masterkey'
    .venv3.14\Scripts\python.exe docs\examples\connection.py
"""

import sys
from decimal import Decimal
from typing import ClassVar, Optional

from pydantic import Field

from rhosocial.activerecord.backend.impl.firebird.backend import FirebirdBackend
from rhosocial.activerecord.backend.impl.firebird.config import FirebirdConnectionConfig
from rhosocial.activerecord.base.field_proxy import FieldProxy
from rhosocial.activerecord.model import ActiveRecord

TABLE = "FB_DEMO_ORDERS"

INSTRUCTIONS = """\
No Firebird database is configured. Set these variables first:

  FIREBIRD_HOST      = 'localhost'
  FIREBIRD_PORT      = '3050'
  FIREBIRD_DATABASE  = '/var/lib/firebird/data/test.fdb'
  FIREBIRD_USERNAME  = 'SYSDBA'
  FIREBIRD_PASSWORD  = 'masterkey'

The database must already exist; this example does not create one.
"""


class Order(ActiveRecord):
    """A declarative model mapped onto a Firebird identity-keyed table."""

    __table_name__ = TABLE
    __primary_key__ = "id"

    c: ClassVar[FieldProxy] = FieldProxy()

    id: Optional[int] = None  # GENERATED BY DEFAULT AS IDENTITY
    code: str = Field(min_length=1, max_length=32)
    total: Decimal = Decimal("0.00")


def resolve_config():
    config = FirebirdConnectionConfig.from_env()
    if not config.database:
        return None
    return config


def main() -> int:
    config = resolve_config()
    if config is None:
        print(INSTRUCTIONS, file=sys.stderr)
        return 2

    backend = FirebirdBackend(connection_config=config)
    try:
        backend.connect()
    except Exception as exc:
        print(f"Could not connect to Firebird: {exc}", file=sys.stderr)
        print(INSTRUCTIONS, file=sys.stderr)
        return 2

    created_table = False
    try:
        version = backend.get_server_version()
        print(f"Connected to Firebird {'.'.join(str(v) for v in version)}")

        # Firebird has no CREATE TABLE IF NOT EXISTS, so ask the catalogue first.
        if not backend.introspector.table_exists(TABLE):
            backend.execute(
                f"CREATE TABLE {TABLE} ("
                "ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                "CODE VARCHAR(32) NOT NULL, "
                "TOTAL NUMERIC(10,2) NOT NULL DEFAULT 0.00)",
                fetch=False,
            )
            created_table = True
            print(f"Created {TABLE}")
        else:
            print(f"Using existing {TABLE}")

        # Configure the model with THIS backend's config and class.
        Order.configure(config, FirebirdBackend)

        # CREATE — the identity value is assigned by Firebird and backfilled.
        order = Order(code="A-1000", total=Decimal("19.99"))
        order.save()
        print(f"Inserted order id={order.id}")

        # READ — FieldProxy builds the Firebird-flavoured predicate.
        rows = Order.query().where(Order.c.code == "A-1000").all()
        print(f"Queried {len(rows)} row(s): {[r.code for r in rows]}")

        # UPDATE — a second save() performs an UPDATE keyed by the identity.
        order.total = Decimal("29.99")
        order.save()
        print(f"Updated order id={order.id} total={order.total}")

        # DELETE
        order.delete()
        print(f"Deleted order id={order.id}")
        return 0
    finally:
        if created_table:
            try:
                backend.execute(f"DROP TABLE {TABLE}", fetch=False)
            except Exception as exc:
                print(f"Could not drop {TABLE}: {exc}", file=sys.stderr)
        backend.disconnect()


if __name__ == "__main__":
    sys.exit(main())
